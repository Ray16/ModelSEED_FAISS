"""Single source of truth for where the pipeline reads and writes.

The database (mcb.io) is read-only. Everything the pipeline produces is a proposal, laid
out under WORKDIR (the mass_charge_balance/ root, overridable with $MCB_WORKDIR) in four
buckets so the directory reads clearly instead of ~30 loose files:

    inputs/    frozen human/agent inputs the pipeline CONSUMES  (agent_decisions_*,
               kegg_verdicts_refined) -- not regenerated by `mcb run`
    work/      regenerable pipeline intermediates + fixes/      (stage *_corrections,
               candidates, corrections_log inputs, landscape, triage, kegg_cache, ...)
    results/   deliverables                                     (corrected_reactions,
               corrections_log, BALANCE_REPORT, audit_flags)
    figures/   generated .png

Helpers return absolute paths and create the bucket on demand. `inp()` falls back to the
work dir / legacy root location so an input file left in an older layout is still found.
(The buckets are top-level, not under data/, because the repo's .gitignore excludes data/.)
"""
import os
from pathlib import Path

PKG_DIR = Path(__file__).resolve().parent                            # .../mass_charge_balance/mcb
WORKDIR = Path(os.environ.get("MCB_WORKDIR", str(PKG_DIR.parent)))   # .../mass_charge_balance

INPUTS = WORKDIR / "inputs"
WORK = WORKDIR / "work"
RESULTS = WORKDIR / "results"
FIGURES = WORKDIR / "figures"


def _in(d: Path, name: str) -> str:
    d.mkdir(parents=True, exist_ok=True)
    return str(d / name)


def work(name: str) -> str:
    """Regenerable pipeline intermediate (data/work/)."""
    return _in(WORK, name)


def result(name: str) -> str:
    """Deliverable (results/)."""
    return _in(RESULTS, name)


def figure(name: str) -> str:
    """Generated figure (figures/)."""
    return _in(FIGURES, name)


def inp(name: str) -> str:
    """Frozen pipeline input (data/inputs/), with fallback to work/ then legacy root."""
    for cand in (INPUTS / name, WORK / name, WORKDIR / name):
        if cand.exists():
            return str(cand)
    return _in(INPUTS, name)   # default write location if absent


def wp(name: str) -> str:
    """Legacy work-dir-root path (docs and a few top-level files)."""
    return str(WORKDIR / name)
